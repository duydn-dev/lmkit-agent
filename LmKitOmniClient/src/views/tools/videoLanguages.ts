/** Chuan hoa de tim kiem khong phan biet hoa thuong/dau. */
export function normalizeVideoSearch(value: string): string {
  return value.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
}

/** Tim locale theo ma, ten ban dia hoac ten tieng Anh. */
export function filterVideoLanguages(query: string): ReadonlyArray<VideoLanguage> {
  const q = normalizeVideoSearch(query.trim());
  if (!q) return VIDEO_LANGUAGES;
  return VIDEO_LANGUAGES.filter((lang) => normalizeVideoSearch(lang.code).includes(q) || normalizeVideoSearch(lang.nativeName).includes(q) || normalizeVideoSearch(lang.englishName).includes(q));
}

/** Chi chap nhan URL tuyet doi http/https — kiem tra cu phap, khong fetch. */
export function isAllowedVideoSource(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed) return false;
  try {
    const url = new URL(trimmed);
    return url.protocol === 'http:' || url.protocol === 'https:';
  } catch {
    return false;
  }
}

/** Nhan dien URL trang mang xa hoi (khong hua preview chac chan). */
export function isSocialPageUrl(value: string): boolean {
  const lower = value.trim().toLowerCase();
  return lower.includes('facebook.com') || lower.includes('fb.watch') || lower.includes('youtube.com') || lower.includes('youtu.be');
}
